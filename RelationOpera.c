#include<stdio.h>

int main(){
	// Relation Operator, Return 1 if true and return 0 if false;
	int a = 10;
	int b = 20;
	printf("a == b %d\n",(a == b)); // check for equal values
	printf("a != b %d\n",(a != b));
	printf("a > b %d\n",(a > b));
	printf("a < b %d\n",(a < b));
	printf("a >= b %d\n",(a >= b));
	printf("a <= b %d\n",(a <= b));
}
