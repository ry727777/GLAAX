#include<stdio.h>

int main(){
	// Arithmetic Operator
	printf("%d\n",10/20); // Integer Division both are int
	printf("%f\n",10/20.0); // Float division 
	int A = 10;
	int B = 20;
	printf("A + B %d\n",A+B);
	printf("A - B %d\n",A-B);
	printf("A * B %d\n",A*B);
	printf("A / B %d\n",A/B);
	printf("A %% B %d\n",A%B);
}
