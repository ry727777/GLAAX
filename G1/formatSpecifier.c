#include<stdio.h>

int main(){
	// Topic - Format Specifier
	/*
	%d or %i use to print Integer number
	%f used to print decimal or float, %.2f print up to 2 decimal 
	%c used to print char value
	*/
	printf("  %d Hi %.2f Hello %c\n",26,26.578,'A');
	
	printf("My name is Rahul yadav.\n");
	printf("I am %d years old.\n",26);
	printf("I scored %.2f%c in class 12th",84.67,'%');
	
}
